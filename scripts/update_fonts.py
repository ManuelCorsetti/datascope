"""Download the fonts the HTML report embeds into src/datascope/fonts/.

Reports are single files that must render with no network access, so the
fonts are bundled with the package and inlined into every report as data:
URIs (see datascope.html_report). This script regenerates them:

* Roboto and Roboto Mono, Latin + Latin Extended subsets, variable weight
  400-700 (other scripts fall back to the system sans/mono fonts);
* Material Symbols Outlined, subset to only the icons the report template
  uses (the full font is several MB). Rerun this script after adding an
  icon to the template; tests/test_html_report.py fails until you do.

    python scripts/update_fonts.py

Needs network access to fonts.googleapis.com, fonts.gstatic.com and
raw.githubusercontent.com (for the licence texts).
"""
from __future__ import annotations

import re
import sys
import urllib.parse
import urllib.request
from pathlib import Path
from typing import List, Set, Tuple

ROOT = Path(__file__).resolve().parent.parent
FONT_DIR = ROOT / "src" / "datascope" / "fonts"

# Google Fonts serves woff2 only to browsers it recognises; any current
# Chrome user agent will do.
USER_AGENT = ("Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 "
              "(KHTML, like Gecko) Chrome/124.0.0.0 Safari/537.36")
TEXT_FONTS_CSS = "https://fonts.googleapis.com/css2?family=Roboto:wght@400..700&family=Roboto+Mono:wght@400..700"
ICON_FONT_CSS = ("https://fonts.googleapis.com/css2?family=Material+Symbols+Outlined:"
                 "opsz,wght,FILL,GRAD@20..40,400..500,0..1,0")
TEXT_SUBSETS = ("latin", "latin-ext")
LICENCES = {
    "OFL-Roboto.txt": "https://raw.githubusercontent.com/google/fonts/main/ofl/roboto/OFL.txt",
    "OFL-RobotoMono.txt": "https://raw.githubusercontent.com/google/fonts/main/ofl/robotomono/OFL.txt",
    "LICENSE-MaterialSymbols.txt": "https://raw.githubusercontent.com/google/material-design-icons/master/LICENSE",
}


def used_icon_names(template: str) -> Set[str]:
    """Every Material Symbols ligature the report template can render."""
    patterns = [
        r"material-symbols-outlined[^\"]*\"[^>]*>([a-z0-9_]+)<",   # static <span ...>name</span>
        r"\bicon\('([a-z0-9_]+)'",                                 # icon('name', ...)
        r"\bicon\([^;]*?\|\|\s*'([a-z0-9_]+)'",                    # icon(MAP[key] || 'fallback', ...)
        r"\bicon:\s*'([a-z0-9_]+)'",                               # RUN_STATUS entries
        r"\biconName:\s*'([a-z0-9_]+)'",                           # KPI tiles
        r"\bscopeBlock\('([a-z0-9_]+)'",                           # data-quality scope headers
        r"\['[A-Z][^']*',\s*[^'\],][^\]]*?,\s*'([a-z0-9_]+)'\]",   # detail stat rows [label, value, icon]
    ]
    names: Set[str] = set()
    for p in patterns:
        names.update(re.findall(p, template))
    for obj in ("TYPE_ICON", "SEVERITY_ICON"):
        body = re.search(r"const " + obj + r" = \{(.*?)\};", template, re.S)
        if body is None:
            raise ValueError(f"{obj} not found in the report template")
        names.update(re.findall(r":\s*'([a-z0-9_]+)'", body.group(1)))
    return names


def _get(url: str) -> bytes:
    req = urllib.request.Request(url, headers={"User-Agent": USER_AGENT})
    with urllib.request.urlopen(req, timeout=60) as resp:
        return resp.read()


def _font_faces(css: str) -> List[Tuple[str, str]]:
    """(subset comment, @font-face block) pairs from a Google Fonts css2 response."""
    return re.findall(r"/\*\s*([\w-]+)\s*\*/\s*(@font-face\s*\{.*?\})", css, re.S) or \
        [("", block) for block in re.findall(r"@font-face\s*\{.*?\}", css, re.S)]


def _slug(block: str) -> str:
    family = re.search(r"font-family:\s*'([^']+)'", block).group(1)
    return family.lower().replace(" ", "-")


def main() -> None:
    sys.path.insert(0, str(ROOT / "src"))
    from datascope.html_report import _TEMPLATE  # noqa: E402

    icons = sorted(used_icon_names(_TEMPLATE))
    FONT_DIR.mkdir(parents=True, exist_ok=True)
    for old in FONT_DIR.glob("*.woff2"):
        old.unlink()

    rules: List[str] = []
    text_css = _get(TEXT_FONTS_CSS).decode()
    icon_css = _get(ICON_FONT_CSS + "&icon_names=" + urllib.parse.quote(",".join(icons))).decode()
    faces = [(s, b) for s, b in _font_faces(text_css) if s in TEXT_SUBSETS] + _font_faces(icon_css)
    for subset, block in faces:
        url = re.search(r"url\((https://[^)]+)\)", block).group(1)
        name = _slug(block) + (f"-{subset}" if subset else "") + ".woff2"
        data = _get(url)
        (FONT_DIR / name).write_bytes(data)
        rules.append(block.replace(url, name))
        print(f"  {name}: {len(data) / 1024:.1f} KB")

    header = ("/* Generated by scripts/update_fonts.py - do not edit. Roboto and Roboto Mono: SIL Open Font\n"
              "   License 1.1; Material Symbols: Apache License 2.0. Licence texts are in this directory. */\n")
    (FONT_DIR / "fonts.css").write_text(header + "\n".join(rules) + "\n", encoding="utf-8")
    (FONT_DIR / "icons.txt").write_text("\n".join(icons) + "\n", encoding="utf-8")
    for fname, url in LICENCES.items():
        (FONT_DIR / fname).write_bytes(_get(url))
    print(f"Wrote {len(rules)} font faces and {len(icons)} icons to {FONT_DIR.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
